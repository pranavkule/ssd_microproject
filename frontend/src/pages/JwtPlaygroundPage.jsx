import { useMemo, useState } from 'react';
import { gatewayOrigin, getErrorMessage } from '../services/api.js';
import { ErrorBanner, PageHeader, Panel, StatusBadge } from '../components/DashboardUI.jsx';
import { useDashboard } from '../contexts/DashboardContext.jsx';
import { sendJwtTestRequest } from '../utils/jwtPlayground.js';

function JwtPlaygroundPage() {
  const { routes } = useDashboard();
  const availableRoutes = useMemo(
    () => routes.filter((route) => route.enabled && route.methods?.includes('GET')),
    [routes]
  );
  const [selectedId, setSelectedId] = useState('');
  const [token, setToken] = useState('');
  const [sending, setSending] = useState(false);
  const [error, setError] = useState('');
  const [result, setResult] = useState(null);
  const selectedRoute = availableRoutes.find((route) => route.id === selectedId) || availableRoutes[0];

  async function sendRequest(event) {
    event.preventDefault();
    if (!selectedRoute) return;
    setSending(true);
    setError('');
    setResult(null);
    try {
      setResult(await sendJwtTestRequest({
        url: `${gatewayOrigin}${selectedRoute.path}`,
        token,
        authRequired: selectedRoute.authRequired,
      }));
    } catch (requestError) {
      setError(getErrorMessage(requestError));
    } finally {
      setSending(false);
    }
  }

  return (
    <div className="page-stack">
      <PageHeader eyebrow="Live gateway request" title="JWT testing playground" description="Send a real GET request through the gateway. Tokens stay in this page and are never saved or logged by the dashboard." />
      <ErrorBanner message={error} />
      <Panel title="Test a route" description="Choose a route with GET enabled, then compare public, missing-token, invalid-token, or role-protected behavior.">
        {availableRoutes.length === 0 ? <div className="empty-state"><h3>No GET routes available</h3><p>Enable a route with GET in route management to use the playground.</p></div> : (
          <form className="route-form" onSubmit={(event) => void sendRequest(event)}>
            <label className="form-field"><span>API route</span><select value={selectedRoute?.id || ''} onChange={(event) => setSelectedId(event.target.value)}>{availableRoutes.map((route) => <option value={route.id} key={route.id}>{route.name} — GET {route.path}</option>)}</select></label>
            <label className="form-field"><span>JWT bearer token <small className="inline-hint">Optional</small></span><textarea rows="4" autoComplete="off" spellCheck="false" value={token} onChange={(event) => setToken(event.target.value)} placeholder="Paste a token generated by the development utility, or leave empty." /></label>
            <p className="muted-copy">Generate the development user token with <code>npm run auth:token --workspace gateway</code>. The utility only issues the user role; a protected route requiring another role should return 403.</p>
            <div className="form-actions"><button className="button button-primary" type="submit" disabled={sending || !selectedRoute}>{sending ? 'Sending request…' : 'Send request'}</button></div>
          </form>
        )}
      </Panel>
      {result ? <Panel title="Gateway response" description={`GET ${selectedRoute.path}`}>
        <div className="jwt-result-heading"><StatusBadge status={result.verdict.success ? 'healthy' : 'unhealthy'} label={result.verdict.label} /><strong>HTTP {result.status}</strong></div>
        <pre className="jwt-result-body">{typeof result.body === 'string' ? result.body : JSON.stringify(result.body, null, 2)}</pre>
      </Panel> : null}
    </div>
  );
}

export default JwtPlaygroundPage;
